const EN_DISCLAIMER =
  "Results vary. An examination is required to see if this treatment is appropriate. This is not a diagnosis or a guarantee.";
const FR_DISCLAIMER =
  "Les resultats varient. Un examen est requis pour determiner si ce traitement convient. Ceci n'est pas un diagnostic ni une garantie.";

const EN_PRICE_DISCLAIMER =
  "The price mentioned applies only to the described service, subject to examination. Additional care, if needed, is billed separately. Conditions confirmed in clinic.";
const FR_PRICE_DISCLAIMER =
  "Le tarif mentionne s'applique uniquement au service decrit, sous reserve d'un examen. Les soins supplementaires, au besoin, sont factures a part. Conditions confirmees en clinique.";

const RESULT_CLAIM =
  /\b(guaranteed?|garantie|garantit|garanti[es]?|100\s*%|perfect smile|sourire parfait|miracle|risk-?free|sans risque|pain-?free|totally painless|sans douleur garantie|never fail|toujours fonctionn)/i;

const SUPERLATIVE =
  /\b(#1|number one|best dentist|meilleur dentiste|the only dentist|le seul dentiste|most advanced|plus avancee? de (?:quebec|montreal))\b/i;

const TIMELINE_PROMISE =
  /\b(straight(?:en)?(?:ed)? in \d+|redresse[e]? en \d+|in just \d+ (?:days|weeks|months)|en seulement \d+ (?:jours|semaines|mois)|overnight (?:results|whitening)|des (?:le lendemain|resultats immediats garantis))\b/i;

function mentionsPrice(text: string): boolean {
  return /\$\s*\d|\d[\d\s]*\s*(?:\$|cad\b)|%\s*off|%\s*de rabais|\brabais\b|\bpromo\b|\bspecial\b|\boffre\b/i.test(
    text
  );
}

function mentionsTreatment(text: string): boolean {
  return /\b(invisalign|aligner|whitening|blanchiment|veneer|facette|implant|crown|couronne|botox|smile|sourire|treatment|traitement)\b/i.test(
    text
  );
}

function softenClaims(text: string): string {
  let out = text;
  out = out.replace(/\b100\s*%\s*(success|effective|satisfaction)\b/gi, "individual results");
  out = out.replace(/\bguaranteed results\b/gi, "results that vary by person");
  out = out.replace(/\bresults are guaranteed\b/gi, "results vary");
  out = out.replace(/\bgarantit des resultats\b/gi, "les resultats varient");
  out = out.replace(/\bresultats garantis\b/gi, "resultats variables");
  out = out.replace(/\brisk-?free\b/gi, "discussed at your exam");
  out = out.replace(/\bpain-?free guaranteed\b/gi, "comfort is a priority");
  out = out.replace(/\bperfect smile guaranteed\b/gi, "a smile you will discuss together");
  out = out.replace(/\bsourire parfait (garanti|assure)\b/gi, "un sourire a evaluer en consultation");
  out = out.replace(/\bbest dentist(?: in \w+)?\b/gi, "your local dentist");
  out = out.replace(/\bmeilleur(?:e)? dentiste\b/gi, "votre dentiste");
  return out;
}

function hasIdentification(text: string, french: boolean): boolean {
  if (french) {
    return /dentiste\s+g[eé]n[eé]raliste/i.test(text) && /peeling/i.test(text);
  }
  return /general\s+dentist/i.test(text) && /peeling/i.test(text);
}

function appendIdentification(text: string, french: boolean): string {
  const body = text.trim();
  if (hasIdentification(body, french)) return body;
  const line = french ? ODQ_IDENTIFICATION_FR : ODQ_IDENTIFICATION_EN;
  return `${body}\n\n${line}`;
}

function stripForbiddenClaims(text: string): string {
  let out = softenClaims(text);
  out = out.replace(
    /\b(orthodontist|oral surgeon|periodontist|endodontist|prosthodontist|pediatric dentist)\b/gi,
    "general dentist"
  );
  out = out.replace(
    /\b(orthodontiste|chirurgien[- ]dentiste oral|parodontiste|endodontiste|prosthodontiste)\b/gi,
    "dentiste généraliste"
  );
  out = out.replace(
    /\b(Invisalign|smile)\s+specialist\b/gi,
    "general dentist offering clear aligner service"
  );
  out = out.replace(
    /\bsp[eé]cialiste\s+(Invisalign|du sourire)\b/gi,
    "dentiste généraliste offrant un service d'aligneurs"
  );
  out = out.replace(
    /[“"]([^"”]{8,280})[”"]\s*(—|-)?\s*(a patient|one of our patients|Google review|5 stars)/gi,
    ""
  );
  out = out.replace(
    /\b(our patients say|a patient told us|patients tell us|5-star reviews|cinq [eé]toiles)\b/gi,
    "patients often ask us"
  );
  out = out.replace(
    /\b(better than other dentists|unlike other clinics|vs\.? other dentists|#1 (?:in|au) (?:vaudreuil|west island|montreal|qu[eé]bec))\b/gi,
    "at our clinic"
  );
  return out.replace(/[ \t]{2,}/g, " ").trim();
}

function equalizePriceEmphasis(text: string): string {
  if (!mentionsPrice(text)) return text;
  let out = text.replace(/~~([^~]+)~~/g, "$1");
  out = out.replace(/[*_]{1,2}(\$\s*\d[\d.,]*)[*_]{1,2}/g, "$1");
  out = out.replace(
    /\$\s*(\d[\d,]*(?:\.\d{2})?)\s*(?:\/|-|→)\s*\$\s*(\d[\d,]*(?:\.\d{2})?)/g,
    "regular price $$$1 · exceptional price $$$2"
  );
  return out;
}

function ensureServiceWording(text: string): string {
  if (/\bInvisalign\s+clear aligner service\b/i.test(text)) return text;
  return text.replace(/\bInvisalign\b/i, "Invisalign clear aligner service");
}

function cleanCopy(text: string): string {
  return ensureServiceWording(
    equalizePriceEmphasis(stripForbiddenClaims(text))
  );
}

function mergeDisclaimer(existing: string, extra: string): string {
  const a = existing.trim();
  const b = extra.trim();
  if (!b) return a;
  if (!a) return b;
  if (a.toLowerCase().includes(b.slice(0, 24).toLowerCase())) return a;
  return `${a} ${b}`;
}

function scanText(text: string, flags: string[]): void {
  if (RESULT_CLAIM.test(text)) flags.push("softened-result-claim");
  if (SUPERLATIVE.test(text)) flags.push("softened-superiority-claim");
  if (TIMELINE_PROMISE.test(text)) flags.push("timeline-promise-review");
}

export function applyOdqCompliance(ad: GeneratedAdCopy): {
  ad: GeneratedAdCopy;
  flags: string[];
} {
  const flags: string[] = [];
  const all = [
    ad.headline,
    ad.caption,
    ad.shortCaption,
    ad.cta,
    ad.disclaimer,
    ad.paid?.primaryText,
    ad.fr?.headline,
    ad.fr?.caption,
    ad.fr?.shortCaption,
  ]
    .filter(Boolean)
    .join("\n");

  scanText(all, flags);
  const price = mentionsPrice(all);
  const treatment = mentionsTreatment(all) || price;

  const next: GeneratedAdCopy = {
    ...ad,
    headline: cleanCopy(ad.headline),
    caption: appendIdentification(cleanCopy(ad.caption), false),
    shortCaption: cleanCopy(ad.shortCaption),
    cta: cleanCopy(ad.cta),
    disclaimer: ad.disclaimer,
    paid: ad.paid
      ? {
          ...ad.paid,
          primaryText: cleanCopy(ad.paid.primaryText),
          headline: cleanCopy(ad.paid.headline),
          description: cleanCopy(ad.paid.description),
        }
      : ad.paid,
    fr: ad.fr
      ? {
          ...ad.fr,
          headline: cleanCopy(ad.fr.headline),
          caption: appendIdentification(cleanCopy(ad.fr.caption), true),
          shortCaption: cleanCopy(ad.fr.shortCaption),
          cta: cleanCopy(ad.fr.cta),
          disclaimer: ad.fr.disclaimer,
          paid: ad.fr.paid
            ? {
                ...ad.fr.paid,
                primaryText: cleanCopy(ad.fr.paid.primaryText),
                headline: cleanCopy(ad.fr.paid.headline),
                description: cleanCopy(ad.fr.paid.description),
              }
            : ad.fr.paid,
        }
      : ad.fr,
  };

  if (treatment) {
    next.disclaimer = mergeDisclaimer(next.disclaimer, EN_DISCLAIMER);
    if (next.fr) {
      next.fr = {
        ...next.fr,
        disclaimer: mergeDisclaimer(next.fr.disclaimer, FR_DISCLAIMER),
      };
    }
  }
  if (price) {
    flags.push("price-promo");
    next.disclaimer = mergeDisclaimer(
      next.disclaimer,
      `${EN_PRICE_DISCLAIMER} Regular advertised fees remain in effect at least 90 days after last publication.`
    );
    next.disclaimer = mergeDisclaimer(next.disclaimer, ODQ_IDENTIFICATION_EN);
    if (next.fr) {
      next.fr = {
        ...next.fr,
        disclaimer: mergeDisclaimer(
          next.fr.disclaimer,
          `${FR_PRICE_DISCLAIMER} Les tarifs reguliers annonces demeurent en vigueur au moins 90 jours apres la derniere publication.`
        ),
      };
      next.fr.disclaimer = mergeDisclaimer(
        next.fr.disclaimer,
        ODQ_IDENTIFICATION_FR
      );
    }
  }

  return { ad: next, flags: [...new Set(flags)] };
}
